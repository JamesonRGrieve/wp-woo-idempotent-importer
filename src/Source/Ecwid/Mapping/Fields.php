declare(strict_types=1);

namespace IdempotentImporter\Source\Ecwid\Mapping;

use IdempotentImporter\Mapping\LegacyPaths;
use IdempotentImporter\Mapping\Slugs;
use IdempotentImporter\Mapping\Times;
use IdempotentImporter\Source\Ecwid\EcwidAdapter;
use IdempotentImporter\Source\Identity;
use IdempotentImporter\Source\Node;
use IdempotentImporter\Support\Decimal;

/** Field readers shared by the Ecwid mappers, so each Ecwid shape is read in exactly one place. */
final class Fields
{
    /** The store's weight units (formatsAndUnits.weightUnit) → WooCommerce weight units; carats have none. */
    public const WEIGHT_UNITS = ['GRAM' => 'g', 'KILOGRAM' => 'kg', 'OUNCE' => 'oz', 'POUND' => 'lbs'];
    /** A storefront URL with a hashbang (`/#!/`) has no path of its own to redirect. */
    private const HASH = '#';
    private const STREET_LINES = "\n";
    private const PERCENT_PLACES = -2;

    public static function id(string $type, int|string $id): string
    {
        return Identity::of(EcwidAdapter::ID, $type, $id);
    }

    /** The Ecwid id of a node the reader identified (the last part of its identity). */
    public static function sourceId(Node $node): string
    {
        return Identity::sourceId($node->id());
    }

    public static function productId(int $productId): string
    {
        return self::id('Product', $productId);
    }

    /**
     * A variant's identity: a variation (`combination`) by its Ecwid id, which is stable across edits and is
     * what an order item names (`combinationId`); a product without variations has one variant of its own.
     * The product mapper and the order mapper both use this.
     */
    public static function variantId(int|string $productId, ?int $combinationId): string
    {
        return $combinationId === null ? self::id('Variant', "{$productId}-base") : self::id('Variant', $combinationId);
    }

    public static function categoryId(int $categoryId): string
    {
        return self::id('Category', $categoryId);
    }

    public static function customerId(int $customerId): string
    {
        return self::id('Customer', $customerId);
    }

    /** A positive id field (Ecwid sends 0 or leaves it out when nothing is linked); null otherwise. */
    public static function linkedId(Node $node, string $field): ?int
    {
        $id = $node->optionalInt($field);

        return $id !== null && $id > 0 ? $id : null;
    }

    /** Money or a measurement sent as a JSON number, exactly; zero when absent. */
    public static function decimalOrZero(?Node $node, string $field): string
    {
        return $node?->optionalDecimal($field) ?? '0';
    }

    /** An amount Ecwid leaves at zero or out when it isn't set (a minimum subtotal, a weight): null then. */
    public static function setAmount(?Node $node, string $field): ?string
    {
        $amount = $node?->optionalDecimal($field);

        return Decimal::isZero($amount) ? null : $amount;
    }

    /** A timestamp (`2024-09-04 07:20:11 +0000`) as ISO 8601 UTC; null when absent or empty. */
    public static function time(?Node $node, string $field): ?string
    {
        return $node === null ? null : Times::iso($node, $field);
    }

    public static function requiredTime(Node $node, string $field): string
    {
        return Times::requiredIso($node, $field);
    }

    /** A tax rate in percent (Ecwid's `value`) as the fraction WooCommerce's tax lines take. */
    public static function rate(Node $tax): ?string
    {
        $percent = $tax->optionalDecimal('value');

        return $percent === null ? null : Decimal::shift($percent, self::PERCENT_PLACES);
    }

    /** A store weight unit in WooCommerce's units; null for carats (or none). */
    public static function weightUnit(?string $unit): ?string
    {
        return self::WEIGHT_UNITS[strtoupper(trim($unit ?? ''))] ?? null;
    }

    /** The slug an object's page uses: its custom slug, else the generated one, else one made from the name. */
    public static function slug(Node $node, string $name): string
    {
        return $node->optionalString('customSlug') ?? $node->optionalString('autogeneratedSlug') ?? Slugs::fromTitle($name);
    }

    /**
     * The storefront paths an object's URL had, to redirect; none when its URL is a hashbang link (`/#!/…`)
     * or the home page.
     *
     * @return list<string>
     */
    public static function legacyPaths(?string $url): array
    {
        $path = $url === null || str_contains($url, self::HASH) ? null : LegacyPaths::pathOf($url);

        return $path === null ? [] : [$path];
    }

    /**
     * A person (an order's billing or shipping person, a customer's billing person or saved address) in
     * WooCommerce's address shape. The given first and last name are used when Ecwid splits the name (it does
     * when the name has two words or more), else the whole name is the first name; the street's two lines
     * are address lines 1 and 2; the state is its code, else its name.
     *
     * @return array<string, string>
     */
    public static function address(?Node $person): array
    {
        if ($person === null) {
            return [];
        }
        $first = $person->optionalString('firstName');
        $last = $person->optionalString('lastName');
        [$line1, $line2] = array_pad(explode(self::STREET_LINES, $person->optionalString('street') ?? '', 2), 2, '');

        return self::filled([
            'first_name' => $first !== null && $last !== null ? $first : $person->optionalString('name'),
            'last_name' => $first !== null && $last !== null ? $last : null,
            'company' => $person->optionalString('companyName'),
            'address_1' => trim($line1),
            'address_2' => trim($line2),
            'city' => $person->optionalString('city'),
            'state' => $person->optionalString('stateOrProvinceCode') ?? $person->optionalString('stateOrProvinceName'),
            'postcode' => $person->optionalString('postalCode'),
            'country' => $person->optionalString('countryCode'),
            'phone' => $person->optionalString('phone'),
        ]);
    }

    /**
     * Whether an address has somewhere to send things (not just a name or phone).
     *
     * @param array<string, string> $address
     */
    public static function hasStreet(array $address): bool
    {
        return isset($address['address_1']) || isset($address['city']) || isset($address['postcode']);
    }

    /**
     * Ecwid taxes (`[{name, value, total, …}]`, value in percent) as WooCommerce taxes, the amount read from
     * $amountField (else `total`); taxes that charged nothing are left out.
     *
     * @return list<array{title: string, rate: ?string, amount: string}>
     */
    public static function taxes(Node $node, string $field, string $amountField = 'total'): array
    {
        $taxes = [];
        foreach (is_array($node->raw()[$field] ?? null) ? $node->list($field) : [] as $tax) {
            $amount = $tax->optionalDecimal($amountField) ?? $tax->optionalDecimal('total');
            if (!Decimal::isZero($amount)) {
                $taxes[] = ['title' => $tax->optionalString('name') ?? 'Tax', 'rate' => self::rate($tax), 'amount' => $amount ?? '0'];
            }
        }

        return $taxes;
    }

    /**
     * The value of a product's or variation's attribute of an Ecwid attribute type (`UPC`, `BRAND`, …); null
     * when it has none.
     */
    public static function attribute(Node $node, string $type): ?string
    {
        foreach (is_array($node->raw()['attributes'] ?? null) ? $node->list('attributes') : [] as $attribute) {
            if ($attribute->optionalString('type') === $type) {
                return $attribute->optionalString('value');
            }
        }

        return null;
    }

    /**
     * @param array<string, ?string> $fields
     *
     * @return array<string, string>
     */
    private static function filled(array $fields): array
    {
        return array_filter($fields, static fn(?string $value): bool => $value !== null && $value !== '');
    }
}
